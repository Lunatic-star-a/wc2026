-- ── Score Calculation Function ──
create or replace function public.calculate_prediction_points(p_match_id bigint)
returns void as $$
declare
  m public.matches;
  pred record;
  earned integer;
begin
  select * into m from public.matches where id = p_match_id;
  if m is null or m.home_score is null or m.away_score is null then
    return;
  end if;

  for pred in
    select * from public.predictions where match_id = p_match_id
  loop
    earned := 0;
    if pred.home_score = m.home_score and pred.away_score = m.away_score then
      earned := 3;
    elsif sign(pred.home_score - pred.away_score) = sign(m.home_score - m.away_score) then
      earned := 1;
    elsif pred.home_score = pred.away_score and m.home_score = m.away_score then
      earned := 1;
    end if;

    update public.predictions set points = earned where id = pred.id;

    update public.profiles
    set total_points = (select coalesce(sum(points), 0) from public.predictions where user_id = pred.user_id),
        predictions_count = (select count(*) from public.predictions where user_id = pred.user_id)
    where id = pred.user_id;
  end loop;
end;
$$ language plpgsql security definer;

-- ── Auto-settlement trigger: when match finishes, calculate points ──
create or replace function public.auto_settle()
returns trigger as $$
begin
  if new.status = 'finished' and (old.status is null or old.status <> 'finished') then
    perform public.calculate_prediction_points(new.id);
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_auto_settle on public.matches;
create trigger trg_auto_settle
  after update on public.matches
  for each row execute function public.auto_settle();

-- ── Auto-settle on INSERT (for seed data with finished status) ──
create or replace function public.auto_settle_insert()
returns trigger as $$
begin
  if new.status = 'finished' then
    perform public.calculate_prediction_points(new.id);
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_auto_settle_insert on public.matches;
